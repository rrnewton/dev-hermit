#!/usr/bin/env python3
"""Regenerate README.md's verdict table and headline from results.csv.

Keeps the published prose and the published numbers from drifting apart: the
table between the two markers below, and the bolded headline underneath it, are
derived from the manifest by summarize.sh rather than edited by hand.
"""
import re
import subprocess
import sys
import pathlib

here = pathlib.Path(__file__).parent
out = subprocess.run([str(here / 'summarize.sh')], capture_output=True, text=True).stdout.splitlines()

skip = ('native control', '  native', 'default hermit', '  hermit', 'corrected arm', 'CONTROLLED')
rows = [l for l in out[1:] if l.strip() and not any(l.startswith(k) for k in skip)]

md = ["| package | version | native | hermit | hermit `--no-rcb-time` |",
      "|---|---|---|---|---|"]
for l in rows:
    pkg, ver = l[:14].strip(), l[14:30].strip()
    nat, her, nor = l[30:41].strip(), l[41:52].strip(), l[52:].strip()
    if not pkg:
        continue
    md.append(f"| {pkg} | {ver} | {nat} | {her} | {'**' + nor + '**' if nor == 'IDENTICAL' else nor} |")

stats = {}
for l in out:
    for key, pat in (('nat', r'native two-root DIVERGES:\s+(\S+)'),
                     ('nor', r'hermit\+--no-rcb-time IDENTICAL:\s+(\S+)')):
        m = re.search(pat, l)
        if m:
            stats[key] = m.group(1)

readme = here / 'README.md'
s = readme.read_text()
start = s.index("| package | version | native | hermit |")
end = s.index("The control fired on **every** package")
head = (f"\n**{stats['nat']} packages diverge natively across two build roots. "
        f"{stats['nor']} measured in the corrected arm are byte-identical under "
        "`hermit run --strict --no-rcb-time`.**\n\n"
        "*(Table and totals generated by `./regen_readme.py` from `results.csv`;\n"
        "regenerate after any new run.)*\n\n")
readme.write_text(s[:start] + "\n".join(md) + "\n" + head + s[end:])
print(f"regenerated: {stats}", file=sys.stderr)
